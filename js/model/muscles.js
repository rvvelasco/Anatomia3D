// Músculos impares (de la línea media)
function midline() {
  const d = {};
  d.orbicular_boca = () => {
    const ring = [];
    for (let k = 0; k <= 20; k++) {
      const a = (k / 20) * Math.PI * 2;
      ring.push(V(Math.cos(a) * 2.5, 152.4 + Math.sin(a) * 1.0, 8.5 - Math.pow(Math.cos(a), 2) * 0.9));
    }
    return sweep(ring, [0.5, 0.22], { out: V(0, 0, 1), radial: 8, segs: 60, caps: false });
  };
  d.diafragma = () => surface((a, t) => {
    const th = a * Math.PI * 2;
    const sx = Math.sin(th);
    const cz = Math.cos(th);
    const rimY = 112 + 5 * Math.max(0, cz) - (cz < 0 ? -cz * 1.5 : 0);
    const topY = 126.5 + (sx < 0 ? 0.8 : 0) - Math.abs(sx) * 0.5;
    const k = Math.cos((t * Math.PI) / 2);
    const rim = V(sx * 12.2, rimY, 1.2 + cz * (cz > 0 ? 7.6 : 5.4));
    const top = V(sx * 5.5 * k, 0, 1.6 + cz * 4 * k);
    const y = rimY + (topY - rimY) * Math.sin((t * Math.PI) / 2);
    return V(rim.x * (1 - t) + top.x * t, y, rim.z * (1 - t) + top.z * t);
  }, 40, 12);
  return d;
}

export function buildMuscles() {
  const parts = [];
  for (const { s, key } of SIDES) {
    const d = defs(s);
    for (const [id, fn] of Object.entries(d)) {
      if (typeof fn !== 'function') continue;
      parts.push({ key: `${id}_${key}`, id, side: key, geo: fn() });
    }
  }
  for (const [id, fn] of Object.entries(midline())) parts.push({ key: id, id, side: null, geo: fn() });
  return parts;
}
