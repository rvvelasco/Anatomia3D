const SK_C = [0, 164.6, -1.4];
const SK_R = [7.3, 8.6, 9.8];

// Punto sobre la bóveda craneal (u sagital, v lateral, en grados) desplazado `off` cm hacia fuera.
function onSkull(u, v, off = 0.4) {
  const U = (u * Math.PI) / 180;
  const W = (v * Math.PI) / 180;
  const d = V(Math.sin(W), Math.cos(W) * Math.sin(U), Math.cos(W) * Math.cos(U));
  const p = V(SK_C[0] + d.x * SK_R[0], SK_C[1] + d.y * SK_R[1], SK_C[2] + d.z * SK_R[2]);
  const n = V(d.x / SK_R[0], d.y / SK_R[1], d.z / SK_R[2]).normalize();
  return p.addScaledVector(n, off);
}

function ribPt(n, s, t, off = 0) {
  const c = new THREE.CatmullRomCurve3(ribPath(n, s), false, 'centripetal');
  const p = c.getPointAt(t);
  if (off) p.add(V(p.x, 0, p.z - 1.5).normalize().multiplyScalar(off));
  return p;
}

// Dirección perpendicular desde el segmento a-b hacia p (para orientar láminas en miembros).
function radialOut(a, b) {
  const ab = b.clone().sub(a);
  const l2 = ab.lengthSq();
  return (p) => {
    const t = Math.max(0, Math.min(1, p.clone().sub(a).dot(ab) / l2));
    return p.clone().sub(a.clone().addScaledVector(ab, t));
  };
}

// Sistema cilíndrico a lo largo de un segmento del miembro:
// f (0..1) a lo largo, ang en grados (0 anterior, 90 lateral, 180 posterior, 270 medial), r radio.
function limb(a, b, s) {
  const axis = b.clone().sub(a);
  const dir = axis.clone().normalize();
  const ant = V(0, 0, 1).sub(dir.clone().multiplyScalar(dir.z)).normalize();
  const lat = dir.clone().cross(ant).normalize();
  if (lat.x * s < 0) lat.negate();
  const fn = (f, ang, r) => {
    const A = (ang * Math.PI) / 180;
    return a.clone().addScaledVector(axis, f).addScaledVector(ant, Math.cos(A) * r).addScaledVector(lat, Math.sin(A) * r);
  };
  fn.out = radialOut(a, b);
  return fn;
}

const trunkOut = (p) => V(p.x, 0, p.z - 1);

function fus(path, w, h = w, out = null, pow = 0.8, tendon = 0.13) {
  const fw = profile(w[0], w[1], w[2], pow);
  const fh = profile(h[0], h[1], h[2], pow);
  return sweep(path, (t) => [fw(t), fh(t)], { out, radial: 14, segs: Math.max(18, path.length * 9), tendon });
}

const tendon = (path, r = 0.12) => rod(path, r, r * 0.8, r, { radial: 6, tendon: 1 });

